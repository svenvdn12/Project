            <h2 class="title">1. Over deelname & labels</h2>
            <article>
                <details>
                    <summary>
                        <h2>Moet ik een officiële diagnose hebben?</h2>
                    </summary>
                    <p>Nee, zeker niet. Bij Het Chaos Atelier geloven we in herkenning.</p>
                    <p>Als jij je herkent in de eigenschappen van neurodivergentie, ben je meer dan welkom. Wij vragen niet om officiële papieren of labels.</p>
                </details>
            </article>
            <article>
                <details>
                    <summary>
                        <h2>Is er een leeftijdsgrens?</h2>
                    </summary>
                    <p>Op dit moment richten we ons op jongvolwassenen tussen de 18 en 30 jaar. We kijken hier echter niet heel strikt naar:</p>
                    <p>Als je net buiten deze groep valt maar je wel thuis voelt bij de doelgroep, mag je altijd contact opnemen</p>
                </details>
            </article>
            <article>
                <details>
                    <summary>
                        <h2>Wat als ik nog niet zeker weet of ik neurodivergent ben?</h2>
                    </summary>
                    <p>Dat is helemaal oké. Het Chaos Atelier is juist een plek voor ontdekking en herkenning.</p>
                    <p>Veel jongeren bij ons zijn zelf nog aan het uitzoeken hoe hun brein werkt.</p>
                </details>
            </article>
        </div>
        <div class="section-2">
            <h2 class="title">2. Over de sfeer & veiligheid</h2>
            <article>
                <details>
                    <summary>
                        <h2>Is Het Chaos Atelier een vorm van therapie?</h2>
                    </summary>
                    <p>Nee, wij zijn een creatieve community en geen zorginstelling of behandelplek. </p>
                    <p>We focussen op talentherkenning, creatieve expressie en onderlinge ontmoeting in een informele setting..</p>
                </details>
            </article>
            <article>
                <details>
                    <summary>
                        <h2>Ik vind het spannend om voor het eerst te komen. Wat kan ik verwachten?</h2>
                    </summary>
                    <p>Dat snappen we heel goed! Daarom beginnen we altijd met een laagdrempelig kennismakingsgesprek (een 'koffietje') met de host.</p>
                    <p>Zo ken je al een gezicht voordat je de groep instapt en kunnen we al je vragen in rust beantwoorden</p>
                </details>
            </article>
            <article>
                <details>
                    <summary>
                        <h2>Wat als het me tijdens een activiteit even te veel wordt?</h2>
                    </summary>
                    <p>Binnen het team hanteren we de regel dat iedereen zijn eigen 'escapes' mag hebben. Als je je niet oké voelt of je wilt je even</p>
                    <p>terugtrekken uit de groep, hoef je daar nooit verantwoording over af te leggen. Communicatie is bij ons belangrijk, maar jouw grenzen staan voorop.</p>
                </details>
            </article>
        </div>
        <div class="section-3">
            <h2 class="title">3. Praktische zaken</h2>
        <article>
            <details>
                <summary class="no-confirmation">
                    <h2>Wat zijn de kosten voor deelname?</h2>
                </summary>
                <p>We willen de drempel zo laag mogelijk houden en zijn om niet afhankelijk van grote bijdragen van deelnemers</p>
                <p>Om no-shows te beperken, experimenteren we soms met een kleine bijdrage, zoals een strippenkaart van €5 voor meerdere activiteiten.</p>
            </details>
        </article>
        <article>
            <details>
                <summary>
                    <h2>Waar vinden de bijeenkomsten plaats?</h2>
                </summary>
                <p>Op dit moment vinden de meeste activiteiten plaats op locaties in Leiden.</p>
                <p>We hebben echter grote plannen om in de toekomst ook naar andere steden, zoals Delft, uit te breiden.</p>
            </details>
        </article>
        <article>
            <details>
                <summary>
                    <h2>Hoe groot zijn de groepen?</h2>
                </summary>
                <p>We houden het graag overzichtelijk zodat iedereen zich gezien voelt. Een ontmoetingsgroep heeft maximaal 8 deelnemers,  een workshop</p>
                <p>ongeveer 12, en bij sociale uitjes kan de groep wat groter zijn (tot 30 personen).</p>
            </details>
        </article>
        <article>
            <details>
                <summary>
                    <h2>Ik heb geen bevestiging gekregen, wat nu?</h2>
                </summary>
                <p>Check eerst even je spambox. Heb je na 24 uur nog niks gehoord? Stuur ons dan even een berichtje via de mail of LinkedIn.</p>
            </details>
        </article>
        <article>
            <details>
                <summary>
                    <h2>Hoe meld ik me af voor een activiteit?</h2>
                </summary>
                <p>Mocht je onverhoopt niet kunnen, laat het ons dan weten via het e-mailadres of telefoonnummer waar je de bevestiging van hebt</p>
                <p>ontvangen. Zo kunnen we iemand anders blij maken met jouw plekje!.</p>
            </details>
